# Arithmetic Operators 

a=7 
b=4
print("Add = ",a+b) # Addition
print("Sub = ",a-b) # Subtraction
print("Mul = ",a*b) # Multiplication
print("Div = ",a/b) # Division
print("Mod = ",a%b) # Modulus
print("Exp = ",a**b) # Exponentiation

# Assignment Operators
b += 3  # increment the value of b by 3
b -= 3  # decrement the value of b by 3
b *= 3  # multiply the value of b by 3
b /= 3  # divide the value of b by 3
print("b = ",b)

# Comparison Operators
print("a == b:", a == b)  # Equal
print("a != b:", a != b)  # Not equal
print("a > b:", a > b)    # Greater than
print("a < b:", a < b)    # Less than
print("a >= b:", a >= b)  # Greater than or equal
print("a <= b:", a <= b)  # Less than or equal

# logical Operators
x = True
y = False
print("x and y:", x and y)  # Logical AND
print("x or y:", x or y)    # Logical OR
print("not x:", not x)      # Logical NOT





